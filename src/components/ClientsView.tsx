import React, { useState } from 'react';
import { useCRM } from '../context/CRMContext';
import { Client, PricingModel } from '../types';
import {
  Briefcase,
  Plus,
  Search,
  Building2,
  DollarSign,
  Calendar,
  MessageCircle,
  Phone,
  Layers,
  Sparkles,
  Award,
  TrendingUp,
  CheckCircle2,
  RotateCcw,
  Eye,
  Filter,
  ArrowRight,
  UserCheck,
  Tag,
  Clock,
  X
} from 'lucide-react';
import { formatPKR, formatDate, getWhatsAppUrl, getClientRevenue, parseAmount } from '../utils/formatters';

interface ClientsViewProps {
  onOpenNewClientModal: () => void;
  onOpenLeadDetail?: (leadId: string) => void;
}

export const ClientsView: React.FC<ClientsViewProps> = ({
  onOpenNewClientModal,
  onOpenLeadDetail
}) => {
  const {
    clients,
    scopedClients,
    users,
    scopedUsers,
    teams,
    scopedTeams,
    services,
    sources,
    returnClientToLead,
    currentUser,
    pricingModels,
    settings
  } = useCRM();

  const baseUsers = scopedUsers;
  const baseTeams = scopedTeams;

  // Filter Bar state
  const [searchQuery, setSearchQuery] = useState('');
  const [fromDate, setFromDate] = useState('');
  const [toDate, setToDate] = useState('');
  const [selectedUser, setSelectedUser] = useState('All');
  const [selectedTeam, setSelectedTeam] = useState('All');
  const [selectedService, setSelectedService] = useState('All');
  const [selectedSource, setSelectedSource] = useState('All');

  // Applied filter state (when clicking Apply Filter)
  const [appliedFilters, setAppliedFilters] = useState({
    search: '',
    fromDate: '',
    toDate: '',
    user: 'All',
    team: 'All',
    service: 'All',
    source: 'All'
  });

  // Client Details Drawer/Modal
  const [selectedClientDetail, setSelectedClientDetail] = useState<Client | null>(null);

  // Filter application
  const handleApplyFilters = (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    setAppliedFilters({
      search: searchQuery,
      fromDate,
      toDate,
      user: selectedUser,
      team: selectedTeam,
      service: selectedService,
      source: selectedSource
    });
  };

  const handleResetFilters = () => {
    setSearchQuery('');
    setFromDate('');
    setToDate('');
    setSelectedUser('All');
    setSelectedTeam('All');
    setSelectedService('All');
    setSelectedSource('All');

    setAppliedFilters({
      search: '',
      fromDate: '',
      toDate: '',
      user: 'All',
      team: 'All',
      service: 'All',
      source: 'All'
    });
  };

  // Filtered clients list
  const clientList = scopedClients || clients;
  const filteredClients = clientList.filter(c => {
    const f = appliedFilters;

    // Search query: Name, phone, email, business
    if (f.search.trim()) {
      const q = f.search.toLowerCase().trim();
      const matchBiz = (c.businessName || '').toLowerCase().includes(q);
      const matchContact = (c.clientName || '').toLowerCase().includes(q);
      const matchPhone = (c.phone || '').toLowerCase().includes(q);
      const matchEmail = (c.email || '').toLowerCase().includes(q);
      if (!matchBiz && !matchContact && !matchPhone && !matchEmail) return false;
    }

    // Date Range: Converted Date or Start Date
    const cDate = c.convertedDate || c.startDate || '';
    if (f.fromDate && cDate && cDate < f.fromDate) {
      return false;
    }
    if (f.toDate && cDate && cDate > f.toDate) {
      return false;
    }

    // User (Assigned To or Generated By or Closed By)
    if (f.user !== 'All') {
      const matchAssigned = c.assignedToId === f.user || c.assignedToName === f.user;
      const matchGen = c.generatedById === f.user || c.generatedByName === f.user;
      const matchClosed = c.closedById === f.user || c.closedByName === f.user;
      if (!matchAssigned && !matchGen && !matchClosed) return false;
    }

    // Service filter
    if (f.service !== 'All') {
      if (!c.services || !c.services.some(s => s.toLowerCase().includes(f.service.toLowerCase()))) {
        return false;
      }
    }

    // Source filter
    if (f.source !== 'All') {
      if (c.source !== f.source) return false;
    }

    return true;
  });

  // Calculate Metrics
  const activeConvertedCount = clientList.filter(c => c.status === 'Active').length;
  const totalRevenue = clientList.reduce(
    (sum, c) => sum + getClientRevenue(c),
    0
  );

  return (
    <div className="space-y-5 pb-16">
      {/* Top Header matching exact structure */}
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl p-5 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2.5">
            <h1 className="text-xl sm:text-2xl font-extrabold text-slate-900 dark:text-white tracking-tight">
              Converted &amp; Active Clients
            </h1>
            <span className="text-xs font-bold px-2.5 py-0.5 rounded-full bg-emerald-50 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-300 border border-emerald-200 dark:border-emerald-800">
              {activeConvertedCount} active converted clients
            </span>
          </div>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
            Accounts with active software licenses, recurring SaaS subscriptions, and custom project deliveries.
          </p>
        </div>

        <button
          onClick={onOpenNewClientModal}
          className="inline-flex items-center gap-1.5 text-xs font-semibold px-4 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white shadow-xs shadow-indigo-600/20 active:scale-95 transition-all cursor-pointer self-start sm:self-auto"
        >
          <Plus className="w-4 h-4" />
          <span>+ Add Client</span>
        </button>
      </div>

      {/* Comprehensive Filter Bar */}
      <form
        onSubmit={handleApplyFilters}
        className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl p-4 shadow-xs space-y-3"
      >
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2 text-xs font-bold text-slate-700 dark:text-slate-300">
            <Filter className="w-4 h-4 text-indigo-500" />
            <span>Filter Clients</span>
          </div>
          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleResetFilters}
              className="px-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700 text-xs font-semibold text-slate-600 dark:text-slate-400 hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors cursor-pointer"
            >
              Reset
            </button>
            <button
              type="submit"
              className="px-4 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-bold shadow-xs transition-colors cursor-pointer"
            >
              Apply
            </button>
          </div>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 lg:grid-cols-6 gap-2.5 text-xs">
          {/* Search */}
          <div className="lg:col-span-2">
            <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400 mb-1">
              Search
            </label>
            <div className="relative">
              <Search className="w-3.5 h-3.5 text-slate-400 absolute left-2.5 top-1/2 -translate-y-1/2" />
              <input
                type="text"
                value={searchQuery}
                onChange={e => setSearchQuery(e.target.value)}
                placeholder="Name, phone, email, business..."
                className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg pl-8 pr-2.5 py-1.5 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
              />
            </div>
          </div>

          {/* From Date */}
          <div>
            <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400 mb-1">
              From Date
            </label>
            <input
              type="date"
              value={fromDate}
              onChange={e => setFromDate(e.target.value)}
              className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg px-2.5 py-1.5 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500 font-mono"
            />
          </div>

          {/* To Date */}
          <div>
            <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400 mb-1">
              To Date
            </label>
            <input
              type="date"
              value={toDate}
              onChange={e => setToDate(e.target.value)}
              className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg px-2.5 py-1.5 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500 font-mono"
            />
          </div>

          {/* User / Agent */}
          <div>
            <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400 mb-1">
              User
            </label>
            <select
              value={selectedUser}
              onChange={e => setSelectedUser(e.target.value)}
              className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg px-2 py-1.5 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
            >
              <option value="All">{currentUser?.role === 'Employee' ? 'My Clients Only' : 'All Users'}</option>
              {baseUsers.map(u => (
                <option key={u.id} value={u.id}>
                  {u.name}
                </option>
              ))}
            </select>
          </div>

          {/* Service */}
          <div>
            <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400 mb-1">
              Service
            </label>
            <select
              value={selectedService}
              onChange={e => setSelectedService(e.target.value)}
              className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg px-2 py-1.5 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
            >
              <option value="All">All Services</option>
              <option value="Salon Management System">Salon Management</option>
              <option value="Education Management System (premium)">EMS Premium</option>
              <option value="Education Management System (Lite)">EMS Lite</option>
              <option value="Custom Website Development">Custom Website</option>
              <option value="Custom Software Development">Custom Software</option>
            </select>
          </div>
        </div>

        {/* Second Row: Source */}
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-2.5 pt-1">
          <div>
            <label className="block text-[10px] font-bold uppercase tracking-wider text-slate-400 mb-1">
              Lead Source
            </label>
            <select
              value={selectedSource}
              onChange={e => setSelectedSource(e.target.value)}
              className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-lg px-2 py-1.5 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
            >
              <option value="All">All Sources</option>
              {sources.map(src => (
                <option key={src} value={src}>
                  {src}
                </option>
              ))}
            </select>
          </div>
        </div>
      </form>

      {/* Clients Data Table matching exact columns */}
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl shadow-xs overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left border-collapse text-xs">
            <thead>
              <tr className="bg-slate-50 dark:bg-slate-800/60 border-b border-slate-200 dark:border-slate-800 text-slate-500 dark:text-slate-400 font-bold uppercase tracking-wider text-[11px]">
                <th className="p-3.5 min-w-[220px]">Client</th>
                <th className="p-3.5 min-w-[180px]">Services</th>
                <th className="p-3.5 min-w-[120px]">Source</th>
                <th className="p-3.5 min-w-[160px]">Pricing</th>
                <th className="p-3.5 min-w-[130px]">Final Price</th>
                <th className="p-3.5 min-w-[130px]">Generated By</th>
                <th className="p-3.5 min-w-[150px]">Assigned To</th>
                <th className="p-3.5 min-w-[130px]">Closed By</th>
                <th className="p-3.5 min-w-[110px]">Converted</th>
                <th className="p-3.5 min-w-[170px] text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 dark:divide-slate-800/80">
              {filteredClients.length === 0 ? (
                <tr>
                  <td colSpan={10} className="p-12 text-center text-slate-400">
                    <CheckCircle2 className="w-8 h-8 text-slate-300 dark:text-slate-600 mx-auto mb-2" />
                    <p className="font-semibold text-slate-700 dark:text-slate-300">
                      No active client accounts match the criteria.
                    </p>
                  </td>
                </tr>
              ) : (
                filteredClients.map(client => {
                  const waUrl = getWhatsAppUrl(client.phone, client.clientName, client.businessName);

                  return (
                    <tr
                      key={client.id}
                      className="hover:bg-slate-50/80 dark:hover:bg-slate-800/40 transition-colors"
                    >
                      {/* CLIENT: Name & Phone & Business (e.g. Asma Salon | 923352496508 · Salon) */}
                      <td className="p-3.5">
                        <div>
                          <div className="flex items-center gap-1.5">
                            <span className="font-bold text-slate-900 dark:text-white text-xs">
                              {client.businessName}
                            </span>
                            <span className="text-slate-300 dark:text-slate-700 font-bold">|</span>
                            <span className="font-mono text-[11px] text-slate-600 dark:text-slate-400">
                              {client.phone}
                            </span>
                          </div>
                          <div className="flex items-center gap-1.5 text-[11px] text-slate-500 mt-0.5">
                            <span>{client.clientName}</span>
                            {client.city && <span>• {client.city}</span>}
                            <a
                              href={waUrl}
                              target="_blank"
                              rel="noreferrer"
                              title="Direct WhatsApp"
                              className="text-emerald-600 hover:text-emerald-500 transition-colors inline-flex items-center ml-1"
                            >
                              <MessageCircle className="w-3 h-3" />
                            </a>
                          </div>
                        </div>
                      </td>

                      {/* SERVICES */}
                      <td className="p-3.5">
                        <div className="flex flex-wrap gap-1">
                          {client.services && client.services.length > 0 ? (
                            client.services.map(srv => (
                              <span
                                key={srv}
                                className="text-[10px] font-semibold px-2 py-0.5 rounded-md bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 truncate max-w-[170px]"
                              >
                                {srv}
                              </span>
                            ))
                          ) : (
                            <span className="text-[10px] text-slate-400">No Services</span>
                          )}
                        </div>
                      </td>

                      {/* SOURCE */}
                      <td className="p-3.5">
                        <span className="inline-flex items-center gap-1 text-[11px] font-semibold px-2 py-0.5 rounded-md bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700">
                          {client.source || 'Call'}
                        </span>
                      </td>

                      {/* PRICING */}
                      <td className="p-3.5">
                        <span className="inline-block text-[11px] font-semibold px-2 py-0.5 rounded-lg bg-indigo-50 dark:bg-indigo-950/80 text-indigo-700 dark:text-indigo-300 border border-indigo-200 dark:border-indigo-800">
                          {client.pricingModel || 'Monthly Subscription Model'}
                        </span>
                      </td>

                      {/* FINAL PRICE */}
                      <td className="p-3.5 font-bold font-mono text-emerald-600 dark:text-emerald-400 text-xs">
                        {client.currency || 'PKR'} {(client.finalPrice || client.activeRevenuePKR || 0).toLocaleString()}
                      </td>

                      {/* GENERATED BY */}
                      <td className="p-3.5 text-slate-700 dark:text-slate-300 font-medium">
                        {client.generatedByName || 'Super Admin'}
                      </td>

                      {/* ASSIGNED TO */}
                      <td className="p-3.5">
                        <span className="font-semibold text-slate-800 dark:text-slate-200">
                          {client.assignedToName || 'Abdur Rehman Arain'}
                        </span>
                      </td>

                      {/* CLOSED BY */}
                      <td className="p-3.5 text-slate-700 dark:text-slate-300 font-medium">
                        {client.closedByName || 'Super Admin'}
                      </td>

                      {/* CONVERTED */}
                      <td className="p-3.5 font-mono text-slate-600 dark:text-slate-400 text-[11px]">
                        {formatDate(client.convertedDate || client.startDate || new Date().toISOString())}
                      </td>

                      {/* ACTIONS: Details, View Lead, Return */}
                      <td className="p-3.5 text-right">
                        <div className="inline-flex items-center gap-1.5 justify-end">
                          {/* Details Button */}
                          <button
                            onClick={() => setSelectedClientDetail(client)}
                            className="px-2.5 py-1 rounded-lg bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-700 font-semibold text-[11px] transition-colors cursor-pointer"
                          >
                            Details
                          </button>

                          {/* View Lead Button */}
                          {client.leadId && onOpenLeadDetail && (
                            <button
                              onClick={() => onOpenLeadDetail(client.leadId!)}
                              className="px-2.5 py-1 rounded-lg bg-indigo-50 dark:bg-indigo-950/70 text-indigo-700 dark:text-indigo-300 hover:bg-indigo-100 font-semibold text-[11px] transition-colors cursor-pointer border border-indigo-200 dark:border-indigo-800"
                            >
                              View Lead
                            </button>
                          )}

                          {/* Return Button */}
                          <button
                            onClick={() => {
                              if (confirm(`Reverse conversion for "${client.businessName}" and return back to active lead status?`)) {
                                returnClientToLead(client.id);
                              }
                            }}
                            title="Reverse conversion back to active lead pipeline"
                            className="px-2 py-1 rounded-lg bg-rose-50 dark:bg-rose-950/60 text-rose-700 dark:text-rose-300 hover:bg-rose-100 font-semibold text-[11px] transition-colors cursor-pointer border border-rose-200 dark:border-rose-800 inline-flex items-center gap-1"
                          >
                            <RotateCcw className="w-3 h-3" />
                            <span>Return</span>
                          </button>
                        </div>
                      </td>
                    </tr>
                  );
                })
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Client Details Modal */}
      {selectedClientDetail && (
        <div className="fixed inset-0 z-50 overflow-y-auto bg-slate-950/70 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl w-full max-w-xl shadow-2xl p-6 space-y-4">
            <div className="flex items-center justify-between border-b border-slate-200 dark:border-slate-800 pb-3">
              <div>
                <h3 className="text-base font-extrabold text-slate-900 dark:text-white">
                  {selectedClientDetail.businessName}
                </h3>
                <p className="text-xs text-slate-500">
                  Client ID: {selectedClientDetail.id} • Converted: {formatDate(selectedClientDetail.convertedDate || selectedClientDetail.startDate || '')}
                </p>
              </div>
              <button
                onClick={() => setSelectedClientDetail(null)}
                className="p-1.5 text-slate-400 hover:text-slate-600 rounded-lg hover:bg-slate-100 dark:hover:bg-slate-800"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <div className="grid grid-cols-2 gap-3 text-xs">
              <div className="p-3 bg-slate-50 dark:bg-slate-800/60 rounded-xl">
                <span className="text-[10px] text-slate-400 block font-bold uppercase">Contact Person</span>
                <span className="font-semibold text-slate-900 dark:text-white">{selectedClientDetail.clientName}</span>
                <span className="block font-mono text-slate-500">{selectedClientDetail.phone}</span>
              </div>

              <div className="p-3 bg-slate-50 dark:bg-slate-800/60 rounded-xl">
                <span className="text-[10px] text-slate-400 block font-bold uppercase">Commercial Model</span>
                <span className="font-semibold text-indigo-600 dark:text-indigo-400">{selectedClientDetail.pricingModel}</span>
                <span className="block font-mono font-bold text-emerald-600">{selectedClientDetail.currency || 'PKR'} {(selectedClientDetail.finalPrice || selectedClientDetail.activeRevenuePKR || 0).toLocaleString()}</span>
              </div>
            </div>

            {/* Dynamic Custom Fields or Standard Breakdown */}
            {selectedClientDetail.customFieldValues && Object.keys(selectedClientDetail.customFieldValues).length > 0 ? (
              <div className="p-3.5 bg-emerald-50/50 dark:bg-emerald-950/20 rounded-xl border border-emerald-200 dark:border-emerald-800/60 text-xs space-y-2">
                <div className="flex items-center justify-between border-b border-emerald-200/60 dark:border-emerald-800/40 pb-1.5">
                  <span className="text-[10px] font-bold text-emerald-800 dark:text-emerald-300 uppercase">
                    Commercial Fee Breakdown ({selectedClientDetail.pricingModel})
                  </span>
                  <span className="font-mono font-bold text-emerald-700 dark:text-emerald-300 text-xs">
                    Total: {selectedClientDetail.currency || settings?.currencySymbol || 'PKR'} {Number(selectedClientDetail.finalPrice || selectedClientDetail.activeRevenuePKR || 0).toLocaleString()}
                  </span>
                </div>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                  {Object.entries(selectedClientDetail.customFieldValues).map(([k, v]) => {
                    if (v === '' || v === undefined || v === null) return null;
                    const matchedField = pricingModels?.flatMap(pm => pm.fields || []).find(f => f.key === k);
                    const label = matchedField?.label || k.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
                    const isCurrency = matchedField?.type === 'currency' || typeof v === 'number';

                    return (
                      <div key={k} className="flex justify-between items-center py-1 px-2 rounded-lg bg-white/70 dark:bg-slate-900/60 border border-emerald-100 dark:border-emerald-900/40">
                        <span className="text-slate-500 dark:text-slate-400 text-[11px] truncate mr-2">{label}:</span>
                        <span className="font-mono font-semibold text-slate-800 dark:text-slate-200 text-[11px]">
                          {isCurrency && (typeof v === 'number' || !isNaN(Number(v)))
                            ? `${selectedClientDetail.currency || settings?.currencySymbol || 'PKR'} ${Number(v || 0).toLocaleString()}`
                            : String(v)}
                        </span>
                      </div>
                    );
                  })}
                </div>
              </div>
            ) : selectedClientDetail.pricingDetails ? (
              <div className="p-3.5 bg-emerald-50/50 dark:bg-emerald-950/20 rounded-xl border border-emerald-200 dark:border-emerald-800/60 text-xs space-y-1.5">
                <span className="text-[10px] font-bold text-emerald-800 dark:text-emerald-300 uppercase block">Breakdown</span>
                {selectedClientDetail.pricingDetails.oneTimeProjectPrice != null && (
                  <div className="flex justify-between">
                    <span className="text-slate-500">Project Price:</span>
                    <span className="font-mono font-bold">PKR {Number(selectedClientDetail.pricingDetails.oneTimeProjectPrice || 0).toLocaleString()}</span>
                  </div>
                )}
                {selectedClientDetail.pricingDetails.advancePayment != null && (
                  <div className="flex justify-between">
                    <span className="text-slate-500">Advance Paid:</span>
                    <span className="font-mono font-bold text-emerald-600">PKR {Number(selectedClientDetail.pricingDetails.advancePayment || 0).toLocaleString()}</span>
                  </div>
                )}
                {selectedClientDetail.pricingDetails.remainingPayment != null && (
                  <div className="flex justify-between">
                    <span className="text-slate-500">Remaining Balance:</span>
                    <span className="font-mono font-bold text-slate-600">PKR {Number(selectedClientDetail.pricingDetails.remainingPayment || 0).toLocaleString()}</span>
                  </div>
                )}
                {selectedClientDetail.pricingDetails.monthlySubscriptionFee != null && (
                  <div className="flex justify-between">
                    <span className="text-slate-500">Monthly SaaS:</span>
                    <span className="font-mono font-bold text-emerald-600">PKR {Number(selectedClientDetail.pricingDetails.monthlySubscriptionFee || 0).toLocaleString()}/mo</span>
                  </div>
                )}
              </div>
            ) : null}

            {selectedClientDetail.paymentTerms && (
              <div className="text-xs p-3 bg-slate-50 dark:bg-slate-800/50 rounded-xl">
                <span className="font-bold text-slate-700 dark:text-slate-300 block mb-0.5">Payment Terms:</span>
                <span className="text-slate-600 dark:text-slate-400">{selectedClientDetail.paymentTerms}</span>
              </div>
            )}

            {selectedClientDetail.conversionNotes && (
              <div className="text-xs p-3 bg-slate-50 dark:bg-slate-800/50 rounded-xl">
                <span className="font-bold text-slate-700 dark:text-slate-300 block mb-0.5">Conversion Remarks:</span>
                <span className="text-slate-600 dark:text-slate-400">{selectedClientDetail.conversionNotes}</span>
              </div>
            )}

            <div className="flex justify-end pt-2 border-t border-slate-200 dark:border-slate-800">
              <button
                onClick={() => setSelectedClientDetail(null)}
                className="px-4 py-2 rounded-xl bg-slate-900 dark:bg-slate-100 text-white dark:text-slate-900 text-xs font-bold cursor-pointer"
              >
                Close
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};

import React, { useState, useEffect, useMemo } from 'react';
import { useCRM } from '../../context/CRMContext';
import { Lead, Client } from '../../types';
import {
  X,
  CheckCircle2,
  DollarSign,
  Building2,
  UserCheck,
  Tag,
  FileText,
  CreditCard,
  Layers,
  Sparkles,
  Info,
  Calendar
} from 'lucide-react';
import { formatPKR } from '../../utils/formatters';
import { DynamicPricingFieldsForm } from '../common/DynamicPricingFieldsForm';

interface ConvertLeadModalProps {
  isOpen: boolean;
  onClose: () => void;
  lead: Lead | null;
  onSuccess?: () => void;
}

export const ConvertLeadModal: React.FC<ConvertLeadModalProps> = ({
  isOpen,
  onClose,
  lead,
  onSuccess
}) => {
  const { users, assignableUsers, convertLeadToClient, currentUser, pricingModels, settings } = useCRM();
  const availableReps = assignableUsers && assignableUsers.length > 0 ? assignableUsers : (currentUser ? [currentUser] : users);

  // Section A: Closing Info (3 Columns)
  const [generatedById, setGeneratedById] = useState<string>('');
  const [assignedToId, setAssignedToId] = useState<string>('');
  const [closedById, setClosedById] = useState<string>('');

  // Section B: Final Services Multi-Select
  const [selectedServices, setSelectedServices] = useState<string[]>([]);

  // Section C: Dynamic Final Pricing Section
  const [pricingModel, setPricingModel] = useState<string>('One-Time Project Model');
  const [customFieldValues, setCustomFieldValues] = useState<Record<string, any>>({});
  const [finalPrice, setFinalPrice] = useState<number>(80000);
  const [currency, setCurrency] = useState<string>(settings?.currency || 'PKR');

  // One-Time Project Fields (fallback)
  const [oneTimeProjectPrice, setOneTimeProjectPrice] = useState<number>(80000);
  const [advancePayment, setAdvancePayment] = useState<number>(30000);
  const [remainingPayment, setRemainingPayment] = useState<number>(50000);
  const [supportFeeAfterDelivery, setSupportFeeAfterDelivery] = useState<number>(0);
  const [otherFeeAmount, setOtherFeeAmount] = useState<number>(0);
  const [otherFeeDescription, setOtherFeeDescription] = useState<string>('');
  const [pricingNotes, setPricingNotes] = useState<string>('');

  // Monthly Subscription Fields (fallback)
  const [monthlySubscriptionFee, setMonthlySubscriptionFee] = useState<number>(6000);
  const [oneTimeSetupFee, setOneTimeSetupFee] = useState<number>(15000);
  const [monthlySupportFee, setMonthlySupportFee] = useState<number>(0);

  // Ownership Fields (fallback)
  const [ownershipPrice, setOwnershipPrice] = useState<number>(250000);

  // Additional Details
  const [paymentTerms, setPaymentTerms] = useState<string>('');
  const [packageDetails, setPackageDetails] = useState<string>('');
  const [conversionNote, setConversionNote] = useState<string>('');

  const [errorMsg, setErrorMsg] = useState<string>('');

  // Find active pricing model
  const activePricingModel = useMemo(() => {
    return pricingModels?.find(pm =>
      pm.name.toLowerCase() === pricingModel.toLowerCase() ||
      (pricingModel === 'Monthly Subscription Model' && (pm.name.includes('Monthly') || pm.name.includes('Subscription'))) ||
      (pricingModel === 'Ownership Model' && pm.name.includes('Ownership')) ||
      (pricingModel === 'One-Time Project Model' && (pm.name.includes('One-Time') || pm.name.includes('Project')))
    ) || null;
  }, [pricingModel, pricingModels]);

  // Calculate total from dynamic schema fields
  const calculatedTotal = useMemo(() => {
    if (activePricingModel?.fields && activePricingModel.fields.length > 0) {
      return activePricingModel.fields.reduce((acc, f) => {
        if (f.includeInTotal) {
          const val = Number(customFieldValues[f.key] ?? f.defaultValue);
          return acc + (isNaN(val) ? 0 : val);
        }
        return acc;
      }, 0);
    }
    return 0;
  }, [activePricingModel, customFieldValues]);

  // Sync calculated total to final price if available
  useEffect(() => {
    if (calculatedTotal > 0) {
      setFinalPrice(calculatedTotal);
    }
  }, [calculatedTotal]);

  const handleCustomFieldChange = (key: string, value: any) => {
    setCustomFieldValues(prev => ({
      ...prev,
      [key]: value
    }));
  };

  // Standard service options requested
  const STANDARD_SERVICES = [
    'Education Management System (premium)',
    'Education Management System (Lite)',
    'Salon Management System',
    'Custom Website Development',
    'Custom Software Development'
  ];

  // Initialize modal state when lead changes
  useEffect(() => {
    if (lead) {
      // Generated By
      setGeneratedById(lead.assignedToId || (users[0]?.id ?? ''));
      // Assigned To
      setAssignedToId(lead.assignedToId || (users[0]?.id ?? ''));
      // Closed By (Default to current logged in user e.g. Super Admin)
      setClosedById(currentUser?.id || users[0]?.id || '');

      // Services: default to lead services or salon management
      if (lead.services && lead.services.length > 0) {
        setSelectedServices(lead.services);
      } else {
        setSelectedServices(['Salon Management System']);
      }

      // Pre-fill customFieldValues if available
      if (lead.budgetDetails?.customFieldValues) {
        setCustomFieldValues(lead.budgetDetails.customFieldValues);
      } else {
        setCustomFieldValues({
          monthly_fee: lead.budgetDetails?.monthlySubscriptionFee ?? 6000,
          setup_fee: lead.budgetDetails?.oneTimeSetupFee ?? lead.budgetDetails?.setupFee ?? 15000,
          support_fee: lead.budgetDetails?.monthlySupportFee ?? 0,
          ownership_price: lead.budgetDetails?.ownershipPrice ?? 250000,
          project_price: lead.budgetDetails?.totalProjectPrice ?? lead.valuePKR ?? 80000,
          advance_payment: lead.budgetDetails?.advanceMilestoneAmount ?? 30000,
          other_fee: lead.budgetDetails?.otherFeeAmount ?? 0,
          other_fee_desc: lead.budgetDetails?.otherFeeDescription ?? ''
        });
      }

      // Determine Pricing Model
      if (lead.budgetType === 'One-Time Project Model' || lead.pricingModel === 'One-Time Project') {
        setPricingModel('One-Time Project Model');
        const projPrice = lead.budgetDetails?.totalProjectPrice || lead.valuePKR || 80000;
        const adv = lead.budgetDetails?.advanceMilestoneAmount || 30000;
        setOneTimeProjectPrice(projPrice);
        setAdvancePayment(adv);
        setRemainingPayment(Math.max(0, projPrice - adv));
        setFinalPrice(projPrice);
      } else if (lead.budgetType === 'Monthly Subscription Model' || lead.pricingModel === 'Monthly Subscription') {
        setPricingModel('Monthly Subscription Model');
        const sub = lead.budgetDetails?.monthlySubscriptionFee || 6000;
        setMonthlySubscriptionFee(sub);
        setOneTimeSetupFee(lead.budgetDetails?.oneTimeSetupFee || 15000);
        setMonthlySupportFee(lead.budgetDetails?.monthlySupportFee || 0);
        setFinalPrice(lead.budgetDetails?.totalCalculatedValuePKR || sub);
      } else if (lead.budgetType === 'Ownership Model' || lead.pricingModel === 'Ownership Model') {
        setPricingModel('Ownership Model');
        const ownPrice = lead.budgetDetails?.ownershipPrice || 250000;
        setOwnershipPrice(ownPrice);
        setFinalPrice(lead.budgetDetails?.totalCalculatedValuePKR || ownPrice);
      } else {
        setPricingModel(lead.budgetType && lead.budgetType !== 'No Budget Discussed' ? lead.budgetType : 'One-Time Project Model');
        setFinalPrice(lead.budgetDetails?.totalCalculatedValuePKR || lead.valuePKR || 80000);
        setOneTimeProjectPrice(lead.valuePKR || 80000);
        setAdvancePayment(30000);
        setRemainingPayment(Math.max(0, (lead.valuePKR || 80000) - 30000));
      }

      setCurrency(settings?.currency || 'PKR');
      setOtherFeeAmount(lead.budgetDetails?.otherFeeAmount || 0);
      setOtherFeeDescription(lead.budgetDetails?.otherFeeDescription || '');
      setPricingNotes(lead.budgetDetails?.budgetNotes || '');
      setPaymentTerms('');
      setPackageDetails(`${lead.businessName} software package deployment`);
      setConversionNote(`Client finalized with ${lead.name}. Agreed to terms.`);
      setErrorMsg('');
    }
  }, [lead, currentUser, users, isOpen, settings]);

  // Recalculate remaining payment when oneTimeProjectPrice or advancePayment changes
  const handleProjectPriceChange = (val: number) => {
    setOneTimeProjectPrice(val);
    setFinalPrice(val);
    setRemainingPayment(Math.max(0, val - advancePayment));
  };

  const handleAdvancePaymentChange = (val: number) => {
    setAdvancePayment(val);
    setRemainingPayment(Math.max(0, oneTimeProjectPrice - val));
  };

  const toggleService = (srv: string) => {
    if (selectedServices.includes(srv)) {
      if (selectedServices.length > 1) {
        setSelectedServices(selectedServices.filter(s => s !== srv));
      }
    } else {
      setSelectedServices([...selectedServices, srv]);
    }
  };

  const handleModelChange = (model: string) => {
    setPricingModel(model);
    const targetModel = pricingModels?.find(pm => pm.name.toLowerCase() === model.toLowerCase());
    if (targetModel?.fields && targetModel.fields.length > 0) {
      const sum = targetModel.fields.reduce((acc, f) => {
        if (f.includeInTotal) {
          const v = Number(customFieldValues[f.key] ?? f.defaultValue);
          return acc + (isNaN(v) ? 0 : v);
        }
        return acc;
      }, 0);
      if (sum > 0) {
        setFinalPrice(sum);
        return;
      }
    }

    if (model === 'One-Time Project Model') {
      setFinalPrice(oneTimeProjectPrice || 80000);
    } else if (model === 'Monthly Subscription Model') {
      setFinalPrice(monthlySubscriptionFee || 6000);
    } else if (model === 'Ownership Model') {
      setFinalPrice(ownershipPrice || 250000);
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!lead) return;

    if (selectedServices.length === 0) {
      setErrorMsg('Please select at least one service for the client.');
      return;
    }

    if (!finalPrice || finalPrice <= 0) {
      setErrorMsg('Please specify a valid final price.');
      return;
    }

    const genUser = users.find(u => u.id === generatedById);
    const assUser = users.find(u => u.id === assignedToId);
    const clsUser = users.find(u => u.id === closedById);

    const conversionData: Partial<Client> = {
      services: selectedServices,
      pricingModel,
      finalPrice,
      currency: currency || settings?.currency || 'PKR',
      customFieldValues,
      totalCalculatedValuePKR: finalPrice,
      generatedById,
      generatedByName: genUser?.name || 'Super Admin',
      assignedToId,
      assignedToName: assUser?.name || 'Abdur Rehman Arain',
      closedById,
      closedByName: clsUser?.name || 'Super Admin',
      paymentTerms,
      packageDetails,
      conversionNotes: conversionNote,
      pricingDetails: {
        oneTimeProjectPrice: pricingModel === 'One-Time Project Model' ? (Number(customFieldValues.project_price) || oneTimeProjectPrice) : undefined,
        advancePayment: pricingModel === 'One-Time Project Model' ? (Number(customFieldValues.advance_payment) || advancePayment) : undefined,
        remainingPayment: pricingModel === 'One-Time Project Model' ? remainingPayment : undefined,
        supportFeeAfterDelivery: pricingModel === 'One-Time Project Model' ? supportFeeAfterDelivery : undefined,
        otherFeeAmount: otherFeeAmount > 0 ? otherFeeAmount : undefined,
        otherFeeDescription: otherFeeAmount > 0 ? otherFeeDescription : undefined,
        pricingNotes,
        monthlySubscriptionFee: pricingModel === 'Monthly Subscription Model' ? (Number(customFieldValues.monthly_fee) || monthlySubscriptionFee) : undefined,
        setupFee: (pricingModel === 'Monthly Subscription Model' || pricingModel === 'Ownership Model') ? (Number(customFieldValues.setup_fee) || oneTimeSetupFee) : undefined,
        ownershipPrice: pricingModel === 'Ownership Model' ? (Number(customFieldValues.ownership_price) || ownershipPrice) : undefined
      }
    };

    convertLeadToClient(lead.id, conversionData);
    if (onSuccess) onSuccess();
    onClose();
  };

  if (!isOpen || !lead) return null;

  return (
    <div className="fixed inset-0 z-50 overflow-y-auto bg-slate-950/70 backdrop-blur-xs flex items-center justify-center p-3 sm:p-5 animate-in fade-in duration-150">
      <div
        id="convert-lead-modal"
        className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl w-full max-w-3xl shadow-2xl overflow-hidden flex flex-col max-h-[92vh]"
      >
        {/* Modal Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-200 dark:border-slate-800 bg-slate-50/80 dark:bg-slate-800/50">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-emerald-100 dark:bg-emerald-950/80 text-emerald-600 dark:text-emerald-400 flex items-center justify-center font-bold">
              <CheckCircle2 className="w-5 h-5" />
            </div>
            <div>
              <h2 className="text-base sm:text-lg font-extrabold text-slate-900 dark:text-white flex items-center gap-2">
                <span>Convert Lead to Client</span>
                <span className="text-xs font-bold px-2 py-0.5 rounded-full bg-emerald-100 dark:bg-emerald-950 text-emerald-700 dark:text-emerald-300 border border-emerald-300 dark:border-emerald-800">
                  Ready to Close
                </span>
              </h2>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Finalize commercial agreement for <span className="font-bold text-slate-700 dark:text-slate-200">{lead.businessName}</span> ({lead.name})
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-2 text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 rounded-lg hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Body Form */}
        <form onSubmit={handleSubmit} className="p-6 overflow-y-auto space-y-6 flex-1 text-xs">
          {errorMsg && (
            <div className="p-3 rounded-xl bg-rose-50 dark:bg-rose-950/50 border border-rose-200 dark:border-rose-800 text-rose-700 dark:text-rose-300 flex items-center gap-2 text-xs">
              <Info className="w-4 h-4 shrink-0" />
              <span>{errorMsg}</span>
            </div>
          )}

          {/* Section A: Lead Closing Information (3 Columns) */}
          <div className="space-y-2">
            <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 flex items-center gap-1.5">
              <UserCheck className="w-3.5 h-3.5 text-indigo-500" />
              <span>A. Lead Closing Information</span>
            </h3>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
              {/* Lead Generated By */}
              <div>
                <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
                  Lead Generated By *
                </label>
                <select
                  value={generatedById}
                  onChange={e => setGeneratedById(e.target.value)}
                  className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
                  required
                >
                  {users.map(u => (
                    <option key={u.id} value={u.id}>
                      {u.name} — {u.role}
                    </option>
                  ))}
                </select>
              </div>

              {/* Assigned To */}
              <div>
                <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
                  Assigned To *
                </label>
                <select
                  value={assignedToId}
                  onChange={e => setAssignedToId(e.target.value)}
                  className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
                  required
                >
                  {availableReps.map(u => (
                    <option key={u.id} value={u.id}>
                      {u.name} — {u.role}
                    </option>
                  ))}
                </select>
              </div>

              {/* Closed By */}
              <div>
                <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
                  Closed By *
                </label>
                <select
                  value={closedById}
                  onChange={e => setClosedById(e.target.value)}
                  className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
                  required
                >
                  {availableReps.map(u => (
                    <option key={u.id} value={u.id}>
                      {u.name} — {u.role}
                    </option>
                  ))}
                </select>
              </div>
            </div>
          </div>

          {/* Section B: Final Services (Multi-Select Grid) */}
          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 flex items-center gap-1.5">
                <Layers className="w-3.5 h-3.5 text-indigo-500" />
                <span>B. Final Services Included</span>
              </h3>
              <span className="text-[11px] text-slate-400">
                {selectedServices.length} selected
              </span>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
              {STANDARD_SERVICES.map(srv => {
                const isSelected = selectedServices.includes(srv);
                return (
                  <label
                    key={srv}
                    onClick={() => toggleService(srv)}
                    className={`flex items-center gap-2.5 p-2.5 rounded-xl border transition-all cursor-pointer select-none ${
                      isSelected
                        ? 'bg-emerald-50/70 dark:bg-emerald-950/30 border-emerald-300 dark:border-emerald-700 text-emerald-900 dark:text-emerald-200'
                        : 'bg-slate-50 dark:bg-slate-800/50 border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800'
                    }`}
                  >
                    <input
                      type="checkbox"
                      checked={isSelected}
                      onChange={() => {}} // handled by label onClick
                      className="w-4 h-4 rounded text-emerald-600 focus:ring-emerald-500 border-slate-300 dark:border-slate-600 pointer-events-none"
                    />
                    <span className="font-semibold text-xs">{srv}</span>
                  </label>
                );
              })}
            </div>
          </div>

          {/* Section C: Dynamic Final Pricing Section */}
          <div className="space-y-3 p-4 rounded-xl bg-slate-50/70 dark:bg-slate-800/40 border border-slate-200 dark:border-slate-800">
            <div className="flex items-center justify-between">
              <h3 className="text-xs font-bold uppercase tracking-wider text-slate-700 dark:text-slate-300 flex items-center gap-1.5">
                <DollarSign className="w-3.5 h-3.5 text-emerald-500" />
                <span>C. Dynamic Final Pricing Section</span>
              </h3>
              {calculatedTotal > 0 && (
                <span className="text-[11px] font-bold px-2.5 py-0.5 rounded-full bg-emerald-100 dark:bg-emerald-950/80 text-emerald-700 dark:text-emerald-300 border border-emerald-300 dark:border-emerald-800 animate-in fade-in">
                  Total Deal Value: {settings?.currencySymbol || 'Rs.'} {(calculatedTotal || 0).toLocaleString()}
                </span>
              )}
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
              {/* Pricing Model */}
              <div>
                <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
                  Pricing Model *
                </label>
                <select
                  value={pricingModel}
                  onChange={e => handleModelChange(e.target.value)}
                  className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-emerald-500 font-semibold"
                >
                  {pricingModels && pricingModels.length > 0 ? (
                    pricingModels.filter(pm => pm.isActive).map(pm => (
                      <option key={pm.id} value={pm.name}>
                        {pm.name} ({pm.billingType})
                      </option>
                    ))
                  ) : (
                    <>
                      <option value="One-Time Project Model">One-Time Project Model</option>
                      <option value="Monthly Subscription Model">Monthly Subscription Model</option>
                      <option value="Ownership Model">Ownership Model</option>
                    </>
                  )}
                  <option value="Custom Quotation / Hybrid">Custom Quotation / Hybrid</option>
                </select>
              </div>

              {/* Final Price */}
              <div>
                <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
                  Final Price * ({currency})
                </label>
                <input
                  type="number"
                  value={finalPrice || ''}
                  onChange={e => setFinalPrice(Number(e.target.value))}
                  placeholder="e.g. 80000"
                  className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono font-bold text-emerald-600 dark:text-emerald-400 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                  required
                />
              </div>

              {/* Currency */}
              <div>
                <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
                  Currency
                </label>
                <input
                  type="text"
                  value={currency}
                  onChange={e => setCurrency(e.target.value)}
                  className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-bold text-slate-800 dark:text-slate-200 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                />
              </div>
            </div>

            {/* Dynamic Schema Rendering for Active Pricing Model with Custom Fields */}
            {activePricingModel?.fields && activePricingModel.fields.length > 0 && (
              <div className="space-y-3 pt-2 border-t border-slate-200 dark:border-slate-700/60 animate-fadeIn">
                <div className="flex items-center justify-between pb-1">
                  <span className="text-xs font-semibold text-slate-600 dark:text-slate-400">
                    {activePricingModel.name} Fee Fields ({activePricingModel.fields.length} dynamic parameters)
                  </span>
                </div>

                <DynamicPricingFieldsForm
                  fields={activePricingModel.fields}
                  values={customFieldValues}
                  onChange={handleCustomFieldChange}
                  currencySymbol={settings?.currencySymbol || 'Rs.'}
                />

                {/* Pricing / Budget Notes */}
                <div>
                  <label className="block text-[11px] font-medium text-slate-600 dark:text-slate-400 mb-1">
                    Pricing Notes &amp; Delivery Agreements
                  </label>
                  <textarea
                    rows={2}
                    value={pricingNotes}
                    onChange={e => setPricingNotes(e.target.value)}
                    placeholder="Agreed pricing terms, milestone conditions, warranty or deployment notes..."
                    className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl p-2.5 text-xs text-slate-800 dark:text-slate-200 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                  />
                </div>
              </div>
            )}

            {/* Fallback Dynamic Fields for One-Time Project Model */}
            {pricingModel === 'One-Time Project Model' && (!activePricingModel?.fields || activePricingModel.fields.length === 0) && (
              <div className="space-y-3 pt-2 border-t border-slate-200 dark:border-slate-700/60">
                {/* Row 1 (3 Cols) */}
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                  <div>
                    <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                      One-Time Project Price (PKR) *
                    </label>
                    <input
                      type="number"
                      value={oneTimeProjectPrice || ''}
                      onChange={e => handleProjectPriceChange(Number(e.target.value))}
                      placeholder="e.g. 80000"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono font-semibold"
                    />
                  </div>

                  <div>
                    <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                      Advance Payment (PKR)
                    </label>
                    <input
                      type="number"
                      value={advancePayment || ''}
                      onChange={e => handleAdvancePaymentChange(Number(e.target.value))}
                      placeholder="e.g. 30000"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono font-semibold text-emerald-600"
                    />
                  </div>

                  <div>
                    <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                      Remaining Payment (PKR)
                    </label>
                    <input
                      type="number"
                      value={remainingPayment || ''}
                      onChange={e => setRemainingPayment(Number(e.target.value))}
                      placeholder="e.g. 50000"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono font-semibold text-slate-500"
                    />
                  </div>
                </div>

                {/* Row 2 (3 Cols) */}
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                  <div>
                    <label className="block text-[11px] font-medium text-slate-600 dark:text-slate-400 mb-1">
                      Support Fee After Delivery (Optional)
                    </label>
                    <input
                      type="number"
                      value={supportFeeAfterDelivery || ''}
                      onChange={e => setSupportFeeAfterDelivery(Number(e.target.value))}
                      placeholder="e.g. 5000"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono"
                    />
                  </div>

                  <div>
                    <label className="block text-[11px] font-medium text-slate-600 dark:text-slate-400 mb-1">
                      Other Fee Amount (Optional)
                    </label>
                    <input
                      type="number"
                      value={otherFeeAmount || ''}
                      onChange={e => setOtherFeeAmount(Number(e.target.value))}
                      placeholder="0"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono"
                    />
                  </div>

                  <div>
                    <label className="block text-[11px] font-medium text-slate-600 dark:text-slate-400 mb-1">
                      Other Fee Description (Optional)
                    </label>
                    <input
                      type="text"
                      value={otherFeeDescription}
                      onChange={e => setOtherFeeDescription(e.target.value)}
                      placeholder="Domain, SSL, SMS API..."
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs"
                    />
                  </div>
                </div>

                {/* Pricing Notes */}
                <div>
                  <label className="block text-[11px] font-medium text-slate-600 dark:text-slate-400 mb-1">
                    Pricing Notes
                  </label>
                  <textarea
                    rows={2}
                    value={pricingNotes}
                    onChange={e => setPricingNotes(e.target.value)}
                    placeholder="Project payment milestone notes and delivery conditions..."
                    className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl p-2.5 text-xs text-slate-800 dark:text-slate-200 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                  />
                </div>
              </div>
            )}

            {/* Fallback Dynamic Fields for Monthly Subscription Model */}
            {pricingModel === 'Monthly Subscription Model' && (!activePricingModel?.fields || activePricingModel.fields.length === 0) && (
              <div className="space-y-3 pt-2 border-t border-slate-200 dark:border-slate-700/60">
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                  <div>
                    <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                      Monthly Subscription Fee *
                    </label>
                    <input
                      type="number"
                      value={monthlySubscriptionFee || ''}
                      onChange={e => {
                        setMonthlySubscriptionFee(Number(e.target.value));
                        setFinalPrice(Number(e.target.value));
                      }}
                      placeholder="e.g. 6000"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono font-bold text-emerald-600"
                    />
                  </div>

                  <div>
                    <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                      One-Time Setup Fee
                    </label>
                    <input
                      type="number"
                      value={oneTimeSetupFee || ''}
                      onChange={e => setOneTimeSetupFee(Number(e.target.value))}
                      placeholder="e.g. 15000"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono"
                    />
                  </div>

                  <div>
                    <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                      Monthly Support Fee
                    </label>
                    <input
                      type="number"
                      value={monthlySupportFee || ''}
                      onChange={e => setMonthlySupportFee(Number(e.target.value))}
                      placeholder="0"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono"
                    />
                  </div>
                </div>

                <div>
                  <label className="block text-[11px] font-medium text-slate-600 dark:text-slate-400 mb-1">
                    Subscription Terms &amp; Renewal Notes
                  </label>
                  <textarea
                    rows={2}
                    value={pricingNotes}
                    onChange={e => setPricingNotes(e.target.value)}
                    placeholder="Monthly billing cycle details..."
                    className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl p-2.5 text-xs"
                  />
                </div>
              </div>
            )}

            {/* Fallback Dynamic Fields for Ownership Model */}
            {pricingModel === 'Ownership Model' && (!activePricingModel?.fields || activePricingModel.fields.length === 0) && (
              <div className="space-y-3 pt-2 border-t border-slate-200 dark:border-slate-700/60">
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                  <div>
                    <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                      Ownership / License Price *
                    </label>
                    <input
                      type="number"
                      value={ownershipPrice || ''}
                      onChange={e => {
                        setOwnershipPrice(Number(e.target.value));
                        setFinalPrice(Number(e.target.value));
                      }}
                      placeholder="e.g. 250000"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono font-bold text-emerald-600"
                    />
                  </div>

                  <div>
                    <label className="block text-[11px] font-bold text-slate-600 dark:text-slate-400 mb-1">
                      Deployment &amp; Setup Fee
                    </label>
                    <input
                      type="number"
                      value={oneTimeSetupFee || ''}
                      onChange={e => setOneTimeSetupFee(Number(e.target.value))}
                      placeholder="e.g. 25000"
                      className="w-full bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs font-mono"
                    />
                  </div>
                </div>
              </div>
            )}
          </div>

          {/* Section D: Deal Terms, Package & Conversion Note */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            <div>
              <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
                Payment Terms (e.g. 30k Advance, 50k on Go-Live)
              </label>
              <input
                type="text"
                value={paymentTerms}
                onChange={e => setPaymentTerms(e.target.value)}
                placeholder="e.g. 30,000 Advance, 50,000 after deployment"
                className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
              />
            </div>

            <div>
              <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
                Package / Deal Details
              </label>
              <input
                type="text"
                value={packageDetails}
                onChange={e => setPackageDetails(e.target.value)}
                placeholder="e.g. 1 Campus license with 2 biometric devices"
                className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
              />
            </div>
          </div>

          <div>
            <label className="block text-[11px] font-bold text-slate-700 dark:text-slate-300 mb-1">
              Conversion Note
            </label>
            <textarea
              rows={2}
              value={conversionNote}
              onChange={e => setConversionNote(e.target.value)}
              placeholder="Add final conversion details, agreed contract scope, or client remarks..."
              className="w-full bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl p-2.5 text-xs text-slate-900 dark:text-slate-100 focus:outline-none focus:ring-1 focus:ring-indigo-500"
            />
          </div>

          {/* Modal Footer Actions */}
          <div className="flex items-center justify-end gap-3 pt-4 border-t border-slate-200 dark:border-slate-800">
            <button
              type="button"
              onClick={onClose}
              className="px-4 py-2.5 rounded-xl border border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-300 font-semibold text-xs hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors cursor-pointer"
            >
              Cancel
            </button>

            <button
              type="submit"
              className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white font-bold text-xs shadow-md shadow-emerald-600/20 active:scale-95 transition-all cursor-pointer border border-emerald-500"
            >
              <CheckCircle2 className="w-4 h-4" />
              <span>Convert to Client</span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};

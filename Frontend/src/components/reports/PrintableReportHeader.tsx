import React from 'react';
import { UserRole } from '../../types';
import { formatDateTime } from '../../utils/formatters';

interface PrintableReportHeaderProps {
  reportTitle: string;
  userRole?: UserRole;
  userName?: string;
  userEmail?: string;
  dateRange: string;
  filterSummary: string[];
  recordCount?: number;
  companyName?: string;
}

export const PrintableReportHeader: React.FC<PrintableReportHeaderProps> = ({
  reportTitle,
  userRole,
  userName,
  userEmail,
  dateRange,
  filterSummary,
  recordCount,
  companyName
}) => {
  const generatedAt = formatDateTime(new Date());

  return (
    <div className="hidden print:block mb-6 border-b-2 border-slate-800 pb-4">
      {/* Top Banner */}
      <div className="flex items-start justify-between">
        <div>
          <div className="flex items-center gap-2">
            <span className="text-xl font-medium tracking-tight text-slate-900 uppercase">
              {companyName ? `${companyName} CRM` : 'Enterprise CRM'}
            </span>
            <span className="text-xs font-bold uppercase tracking-wider px-2 py-0.5 rounded bg-slate-100 text-slate-700 border border-slate-300">
              Executive Report
            </span>
          </div>
          <h1 className="text-2xl font-medium text-slate-900 mt-2 tracking-tight">
            {reportTitle}
          </h1>
        </div>

        <div className="text-right text-xs text-slate-600 space-y-0.5">
          <p className="font-bold text-slate-800">{companyName || 'Enterprise'} Business Operations</p>
          <p>Generated: {generatedAt}</p>
          {recordCount !== undefined && (
            <p className="font-semibold text-slate-700">Total Scoped Records: {recordCount}</p>
          )}
        </div>
      </div>

      {/* Metadata Grid */}
      <div className="grid grid-cols-3 gap-3 mt-4 pt-3 border-t border-slate-200 text-xs text-slate-700">
        <div>
          <span className="font-bold text-slate-900 block text-[11px] uppercase tracking-wider">
            Scope &amp; Authority
          </span>
          <p>{userRole ? `${userRole} Access` : 'Authorized CRM Access'}</p>
        </div>

        <div>
          <span className="font-bold text-slate-900 block text-[11px] uppercase tracking-wider">
            Date Interval
          </span>
          <p>{dateRange || 'All Time'}</p>
        </div>

        <div>
          <span className="font-bold text-slate-900 block text-[11px] uppercase tracking-wider">
            Generated By
          </span>
          <p>{userName || 'CRM User'} {userEmail ? `(${userEmail})` : ''}</p>
        </div>
      </div>

      {/* Active Filter Strip */}
      {filterSummary.length > 0 && (
        <div className="mt-3 pt-2 border-t border-slate-200 text-xs">
          <span className="font-bold text-slate-900 mr-2">Active Applied Filters:</span>
          <span className="text-slate-700">{filterSummary.join('  •  ')}</span>
        </div>
      )}
    </div>
  );
};

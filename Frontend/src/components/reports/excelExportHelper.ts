import * as XLSX from 'xlsx';

export interface ExcelExportPayload {
  fileName: string;
  reportTitle: string;
  scope: string;
  dateRange: string;
  generatedBy: string;
  filterSummary: string[];
  headers: string[];
  rows: (string | number)[][];
}

/**
 * Enterprise Excel (.xlsx) exporter for CRM Reports Center.
 * Uses SheetJS to generate genuine native Microsoft Excel workbooks
 * with proper numeric cells, branded headers, and filter audit metadata.
 */
export function exportToExcel(payload: ExcelExportPayload): void {
  const wb = XLSX.utils.book_new();

  const generatedAt = new Date().toLocaleString('en-US', {
    dateStyle: 'medium',
    timeStyle: 'short'
  });

  const filterText = payload.filterSummary.length > 0
    ? payload.filterSummary.join(' | ')
    : 'All Records (No filters applied)';

  // Header metadata rows
  const metaRows: any[][] = [
    ['iSysware CRM — Official Business Report'],
    [`Report Title: ${payload.reportTitle}`],
    [`Scope Authority: ${payload.scope}`, `Date Range: ${payload.dateRange}`],
    [`Generated By: ${payload.generatedBy}`, `Generated At: ${generatedAt}`],
    [`Active Filters: ${filterText}`],
    [], // Blank spacing row
    payload.headers
  ];

  // Combine metadata and data rows
  const allRows = [...metaRows, ...payload.rows];

  // Create worksheet
  const ws = XLSX.utils.aoa_to_sheet(allRows);

  // Auto-calculate column widths
  const colWidths = payload.headers.map((h, colIdx) => {
    let maxLen = h.length;
    for (const r of payload.rows) {
      const val = (r as any[])[colIdx];
      if (val !== undefined && val !== null) {
        const str = typeof val === 'number' ? val.toLocaleString() : String(val);
        if (str.length > maxLen) maxLen = str.length;
      }
    }
    return { wch: Math.min(Math.max(maxLen + 4, 15), 50) };
  });

  ws['!cols'] = colWidths;

  // Add worksheet to workbook and write
  XLSX.utils.book_append_sheet(wb, ws, 'Report');
  XLSX.writeFile(wb, `${payload.fileName}.xlsx`);
}

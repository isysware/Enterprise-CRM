import XLSX from 'xlsx-js-style';
import { formatDateTime } from '../../utils/formatters';

export interface ExcelExportPayload {
  fileName: string;
  reportTitle: string;
  scope: string;
  dateRange: string;
  generatedBy: string;
  filterSummary: string[];
  headers: string[];
  rows: (string | number)[][];
  companyName?: string;
}

/**
 * VIP Executive Microsoft Excel (.xlsx) Exporter.
 * Formats genuine Excel spreadsheets with:
 * - Branded executive Royal Blue header styling
 * - Crisp borders & alternating zebra rows
 * - Proper typography, alignment, and auto-fitted column widths
 */
export function exportToExcel(payload: ExcelExportPayload): void {
  const wb = XLSX.utils.book_new();

  const generatedAt = formatDateTime(new Date());

  const filterText = payload.filterSummary.length > 0
    ? payload.filterSummary.join(' | ')
    : 'All Records (No filters applied)';

  // Header metadata block
  const metaRows: any[][] = [
    [`${payload.companyName || 'Enterprise'} CRM — Official Business Report`],
    [`Report Title: ${payload.reportTitle}`],
    [`Scope Authority: ${payload.scope}  |  Date Range: ${payload.dateRange}`],
    [`Generated By: ${payload.generatedBy}  |  Exported At: ${generatedAt}`],
    [`Active Filters: ${filterText}`],
    [], // Blank spacer row
    payload.headers
  ];

  // Combine metadata and data rows
  const allRows = [...metaRows, ...payload.rows];

  // Create base worksheet
  const ws = XLSX.utils.aoa_to_sheet(allRows);

  const headerRowIndex = 6; // Index of the table headers (7th row)
  const totalCols = payload.headers.length;
  const totalRows = allRows.length;

  // Auto-calculate column widths
  const colWidths = payload.headers.map((h, colIdx) => {
    let maxLen = h.length;
    for (const r of payload.rows) {
      const val = (r as any[])[colIdx];
      if (val !== undefined && val !== null) {
        const str = typeof val === 'number' ? val.toLocaleString() : String(val);
        if (str.length > maxLen) maxLen = str.length;
      }
    }
    return { wch: Math.min(Math.max(maxLen + 6, 16), 55) };
  });
  ws['!cols'] = colWidths;

  // Row heights
  const rowHeights: { hpt: number }[] = [];
  rowHeights[0] = { hpt: 30 }; // Title banner
  rowHeights[1] = { hpt: 20 }; // Report Title
  rowHeights[2] = { hpt: 18 }; // Scope & Date
  rowHeights[3] = { hpt: 18 }; // Generated By
  rowHeights[4] = { hpt: 18 }; // Filters
  rowHeights[5] = { hpt: 12 }; // Spacer
  rowHeights[headerRowIndex] = { hpt: 28 }; // Main table headers

  for (let r = headerRowIndex + 1; r < totalRows; r++) {
    rowHeights[r] = { hpt: 22 }; // Data rows
  }
  ws['!rows'] = rowHeights;

  // Title Banner Styling (A1)
  const a1Cell = ws[XLSX.utils.encode_cell({ r: 0, c: 0 })];
  if (a1Cell) {
    a1Cell.s = {
      font: { name: 'Calibri', sz: 14, bold: true, color: { rgb: '1E3A8A' } },
      alignment: { vertical: 'center' }
    };
  }

  // Report Title Styling (A2)
  const a2Cell = ws[XLSX.utils.encode_cell({ r: 1, c: 0 })];
  if (a2Cell) {
    a2Cell.s = {
      font: { name: 'Calibri', sz: 12, bold: true, color: { rgb: '2563EB' } },
      alignment: { vertical: 'center' }
    };
  }

  // Meta rows styling (A3, A4, A5)
  for (let r = 2; r <= 4; r++) {
    const metaCell = ws[XLSX.utils.encode_cell({ r, c: 0 })];
    if (metaCell) {
      metaCell.s = {
        font: { name: 'Calibri', sz: 10, italic: r === 2, color: { rgb: '475569' } },
        alignment: { vertical: 'center' }
      };
    }
  }

  // TABLE HEADER ROW (Row index 6) - VIP Royal Blue Background with Crisp White Text
  for (let c = 0; c < totalCols; c++) {
    const cellRef = XLSX.utils.encode_cell({ r: headerRowIndex, c });
    const cell = ws[cellRef];
    if (cell) {
      cell.s = {
        fill: {
          patternType: 'solid',
          fgColor: { rgb: '2563EB' } // Royal Blue
        },
        font: {
          name: 'Calibri',
          sz: 11,
          bold: true,
          color: { rgb: 'FFFFFF' } // Clean White
        },
        alignment: {
          vertical: 'center',
          horizontal: 'center',
          wrapText: true
        },
        border: {
          top: { style: 'thin', color: { rgb: '1D4ED8' } },
          bottom: { style: 'medium', color: { rgb: '1E3A8A' } },
          left: { style: 'thin', color: { rgb: '60A5FA' } },
          right: { style: 'thin', color: { rgb: '60A5FA' } }
        }
      };
    }
  }

  // DATA ROWS (Row index 7 to end) - Elegant Alternating Zebra Styling with Light Borders
  for (let r = headerRowIndex + 1; r < totalRows; r++) {
    const isOdd = (r - headerRowIndex) % 2 === 1;
    const bgRgb = isOdd ? 'FFFFFF' : 'F8FAFC'; // Soft faint slate tint for zebra striping

    for (let c = 0; c < totalCols; c++) {
      const cellRef = XLSX.utils.encode_cell({ r, c });
      const cell = ws[cellRef];
      if (cell) {
        const isNumber = typeof cell.v === 'number';
        cell.s = {
          fill: {
            patternType: 'solid',
            fgColor: { rgb: bgRgb }
          },
          font: {
            name: 'Calibri',
            sz: 10,
            color: { rgb: '0F172A' }
          },
          alignment: {
            vertical: 'center',
            horizontal: isNumber ? 'right' : 'left'
          },
          border: {
            top: { style: 'thin', color: { rgb: 'E2E8F0' } },
            bottom: { style: 'thin', color: { rgb: 'E2E8F0' } },
            left: { style: 'thin', color: { rgb: 'E2E8F0' } },
            right: { style: 'thin', color: { rgb: 'E2E8F0' } }
          }
        };
      }
    }
  }

  // Append styled sheet to workbook and save native .xlsx
  XLSX.utils.book_append_sheet(wb, ws, 'Report Data');
  XLSX.writeFile(wb, `${payload.fileName}.xlsx`);
}
